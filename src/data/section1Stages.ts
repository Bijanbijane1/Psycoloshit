// Helper functions for stage progression
export function getUnlockedStageNumber(completedStages?: Record<number, any>): number {
  if (!completedStages || Object.keys(completedStages).length === 0) {
    return 1; // Stage 1 is initially unlocked
  }
  // Find highest consecutive completed stage + 1
  let nextStage = 1;
  while (completedStages[nextStage] !== undefined) {
    nextStage++;
  }
  return Math.min(nextStage, 100);
}

export function isStageUnlocked(stageNumber: number, completedStages?: Record<number, any>): boolean {
  if (stageNumber === 1) return true;
  // Stage N is unlocked if stage N-1 is completed
  return !!completedStages && !!completedStages[stageNumber - 1];
}
